def translate(key: str, locale: Locale = 'ru', **values: str) -> str:
    return MESSAGES[key][locale == 'kk'].format(**values)


def field_label(field: str, locale: Locale) -> str:
    return FIELD_LABELS[field][locale == 'kk']


def resolve_locale(accept_language: str | None = None) -> Locale:
    preferences = []
    for position, item in enumerate((accept_language or '').split(',')):
        tag, *params = item.strip().lower().split(';')
        language = tag.split('-')[0]
        try:
            quality = next((float(p.strip()[2:]) for p in params if p.strip().startswith('q=')), 1.0)
        except ValueError:
            continue
        if language in ('ru', 'kk') and 0 < quality <= 1:
            preferences.append((quality, -position, language))
    return max(preferences)[2] if preferences else 'ru'


def request_locale(accept_language: Annotated[str | None, Header()] = None) -> Locale:
    return resolve_locale(accept_language)


Language = Annotated[Locale, Depends(request_locale)]
